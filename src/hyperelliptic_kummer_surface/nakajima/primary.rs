use std::collections::{btree_map::Entry, BTreeMap};

use crate::complex::MAX_PIVOT_CELLS;
use crate::error::{Error, Result};
use crate::lee_linear::{Echelon, Vector};
use crate::model::Model;
use crate::syntax::{Label, ParsedExpr};

use super::{coordinate_range, graded_basis::graded_basis, Grade, Monomial, State};

pub(crate) enum Command {
    Dimension(Label, i128, i128),
    IsPrimary(Box<ParsedExpr>),
}

pub(crate) fn dimension(model: &mut Model, grade: &Grade) -> Result<usize> {
    solve(model, grade, None).map(|(dimension, _)| dimension)
}

pub(crate) fn generator(model: &mut Model, grade: &Grade, index: usize) -> Result<State> {
    solve(model, grade, Some(index))?.1.ok_or_else(bad_index)
}

fn solve(
    model: &mut Model,
    grade: &Grade,
    generator: Option<usize>,
) -> Result<(usize, Option<State>)> {
    let basis = graded_basis(model, grade)?;
    if generator.is_some_and(|index| index >= basis.len()) {
        return Err(bad_index());
    }
    let mut rows = BTreeMap::new();
    let mut row_cells = 0;
    let mut echelon = Echelon::default();
    let mut dimension = 0;
    for (column, monomial) in basis.iter().enumerate() {
        let state = State {
            terms: BTreeMap::from([(monomial.clone(), 1)]),
        };
        let mut image = Vec::new();
        // Over Q the positive Virasoro algebra is generated by L_1 and L_2.
        for index in [1, 2] {
            for (target, coefficient) in state.virasoro(model, index, grade.length)?.terms {
                model.spend(1 + target.len())?;
                let next_row = rows.len();
                let row = match rows.entry((index, target)) {
                    Entry::Occupied(entry) => *entry.get(),
                    Entry::Vacant(entry) => {
                        row_cells += 6 + 5 * entry.key().1.len();
                        if row_cells > MAX_PIVOT_CELLS {
                            return Err(Error::plain(
                                "Nakajima primary calculation exceeds the joint Virasoro matrix storage limit",
                            ));
                        }
                        *entry.insert(next_row)
                    }
                };
                image.push((row, coefficient));
            }
        }
        image.sort_unstable_by_key(|entry| entry.0);
        let witness = if generator.is_some() {
            vec![(column, 1)]
        } else {
            Vec::new()
        };
        if let Some(dependence) = echelon.insert(model, image, witness)? {
            // The current column is the free coordinate. Earlier dependencies
            // are never used as pivots, giving the usual nullspace basis.
            if generator == Some(dimension) {
                return Ok((dimension, Some(primitive_state(model, &basis, dependence)?)));
            }
            dimension += 1;
        }
    }
    Ok((dimension, None))
}

fn primitive_state(model: &mut Model, basis: &[Monomial], dependence: Vector) -> Result<State> {
    let (_, first) = dependence
        .first()
        .expect("the relation contains its free coordinate");
    let negate = *first < 0;
    let mut terms = BTreeMap::new();
    for (index, coefficient) in dependence {
        model.spend(1 + basis[index].len())?;
        let coefficient = if negate {
            coefficient.checked_neg().ok_or_else(coordinate_range)?
        } else {
            coefficient
        };
        terms.insert(basis[index].clone(), coefficient);
    }
    Ok(State { terms })
}

fn bad_index() -> Error {
    Error::plain("Nakajima primary generator index is out of range")
}
