#!/usr/bin/env python3
"""Print an ASL presentation of L(3,1) and its signed fundamental cycle."""

import argparse
from collections import Counter
from itertools import permutations, product


def translate(face, shift):
    return tuple(sorted(v // 9 * 9 + (v % 9 + 3 * shift) % 9 for v in face))


def representative(face):
    return min(translate(face, shift) for shift in range(3))


def circle(offset):
    vertices = [(offset + i,) for i in range(9)]
    edges = [(offset + i, offset + (i + 1) % 9) for i in range(9)]
    return [()] + vertices + edges


def sign(permutation):
    return (-1) ** sum(a > b for i, a in enumerate(permutation) for b in permutation[i + 1 :])


def lens():
    # C3 acts freely on the join of two circles by rotating both simultaneously.
    faces = sorted(
        {representative(a + b) for a, b in product(circle(0), circle(9)) if a or b},
        key=lambda face: (len(face), face),
    )
    ids = {face: i for i, face in enumerate(faces)}
    arrows = {}
    for i, face in enumerate(faces):
        for j, larger in enumerate(faces):
            if len(face) >= len(larger):
                continue
            lifts = [
                shift for shift in range(3)
                if set(translate(face, shift)).issubset(larger)
            ]
            assert len(lifts) <= 1
            if lifts:
                arrows[i, j] = lifts[0]
    covers = [edge for edge in arrows if len(faces[edge[1]]) == len(faces[edge[0]]) + 1]

    # A positively oriented facet is the join of two forward polygon edges.
    cycle = Counter()
    for i, j in product(range(3), range(9)):
        facet = (i, (i + 1) % 9, 9 + j, 9 + (j + 1) % 9)
        for perm in permutations(range(4)):
            flag = tuple(
                ids[representative(tuple(facet[i] for i in perm[:length]))]
                for length in range(1, 5)
            )
            cycle[flag] += sign(perm)
    boundary = Counter()
    for flag, value in cycle.items():
        for i in range(4):
            boundary[flag[:i] + flag[i + 1 :]] += (-1) ** i * value
    assert all(x == 0 for x in boundary.values())
    assert set(cycle.values()) == {-1, 1}
    assert (len(faces), len(covers), len(cycle)) == (120, 336, 648)
    return faces, arrows, covers, dict(sorted(cycle.items()))


def rows(entries, width):
    entries = list(entries)
    for i in range(0, len(entries), width):
        print("  " + ",".join(map(str, entries[i : i + width])) + ",")


def point(i):
    return f"x{i:03}"


def edge(i, j):
    return f"{point(i)}<{point(j)}"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--gauge", action="store_true", help="include two explicit gauge-related flats")
    args = parser.parse_args()
    faces, arrows, covers, cycle = lens()
    print("// Generated by examples/dijkgraaf-witten-lens.py.")
    print("space Lens {")
    rows((point(i) for i in range(len(faces))), 12)
    rows((edge(i, j) for i, j in covers), 8)
    print("};")
    print("rvgroup G[3];")
    print("rvdwcoeff P[G,3];")
    carry = [a * ((b + c) // 3) for a, b, c in product((1, 2), repeat=3)]
    print("let k=rvPostnikovCochain[P,3]{" + ",".join(map(str, carry)) + "};")
    print("let changed=rvPostnikovGauge(k,rvPostnikovCochain[P,2]{1,2,0,0});")
    for name, cocycle, orientation in [
        ("Forward", "k", 1),
        ("Reverse", "k", -1),
        ("Untwisted", "zero[RVPostnikovCochain(P,3)]", 1),
        ("Shifted", "changed", 1),
    ]:
        print(f"rvdw {name}[Lens,P]({cocycle}){{")
        rows((orientation * x for x in cycle.values()), 36)
        print("};")
    print("let z=rvDWValue[Forward];")
    print("let one=rvCyclo[3,0];")
    print("let two_zeta=rvCycloScale[2](rvCyclo[3,1]);")
    print("assert z==rvCycloRat[3](add(one,two_zeta));")
    print("assert rvDWValue[Reverse]==rvCycloQGalois[-1](z);")
    print("assert rvDWValue[Untwisted]==rvCycloRat[1](one);")
    print("assert rvDWValue[Shifted]==z;")
    print("show z;show rvDWValue[Reverse];show rvDWValue[Untwisted];")
    print("rvDWComponent[Forward,0];")
    for i in range(3):
        print(f"rvDWClass[Forward,0,{i}];")
    if args.gauge:
        for name, use_gauge in [("Cover", False), ("ChangedCover", True)]:
            print(f"rvflat {name}[Lens,P]{{")
            rows(
                (f"{edge(i, j)}:{(arrows[i, j] + (i * i - j * j if use_gauge else 0)) % 3}"
                 for i, j in covers),
                6,
            )
            print("};")
            for twist in ("k", "changed"):
                print(f"rvDWPhase[{name}]({twist}){{")
                rows(cycle.values(), 36)
                print("};")


if __name__ == "__main__":
    main()
